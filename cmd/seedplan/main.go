// Command seedplan generates the SYNTHETIC order history that is loaded into
// the Shopify development store, together with the outcome the pricing engine
// is expected to produce on it.
//
// Nothing here is real sales data. The demand curves are generated from known
// elasticities (pricing.DemandModel) so that what the store shows can be
// checked against ground truth. Every artefact derived from this plan is
// labelled synthetic.
//
// The plan is deterministic: a fixed random seed and a fixed -end date give
// byte-identical output. `expected` is not hand-written; it is the result of
// running the plan through bridge.Handle (op estimate, then op decide) exactly
// as the Shopify app will.
//
//	go run ./cmd/seedplan -end 2026-11-18 -out shopify-app/seed/plan.json
//	go run ./cmd/seedplan -end 2026-11-18 -check
