func policy() enforcer.Policy {
	return enforcer.Policy{
		ID: "pol_bramble_coffee", Version: 1,
		MarginFloor:      enforcer.MarginFloor{Basis: enforcer.MarginOnPrice, Rate: 4000},
		MaxDecreaseBP:    1500,
		MaxIncreaseBP:    1000,
		Rounding:         enforcer.RoundCharm99,
		MinChangeBP:      200,
		MinConfidenceBP:  6000,
		MaxSKUsChangedBP: 10000,
		Velocity:         enforcer.Velocity{MinDaysBetweenChanges: 14, MaxChangesPerWindow: 2, WindowDays: 90},
		Exclusions:       enforcer.Exclusions{SKUIDs: []string{}, Tags: []string{"subscription"}, Collections: []string{}},
	}
}

// epochDay is the day number the engine's observations use: days since
// 1970-01-01 UTC.
func epochDay(t time.Time) int { return int(t.Unix() / 86400) }

// Build generates the plan for a run date: history covers the historyDays days
// ending the day before runEnd.
func Build(runEnd time.Time) (Plan, error) {
	runEnd = time.Date(runEnd.Year(), runEnd.Month(), runEnd.Day(), 0, 0, 0, 0, time.UTC)
	start := runEnd.AddDate(0, 0, -historyDays)
	last := runEnd.AddDate(0, 0, -1)
	now := runEnd.Add(12 * time.Hour)

	p := Plan{
		Synthetic: true, Label: label, Generator: "cmd/seedplan", Currency: currency,
		History: History{Days: historyDays, Start: start.Format(dayFormat), End: last.Format(dayFormat),
			RunEnd: runEnd.Format(dayFormat), Now: now.Format(time.RFC3339), Seed: seed},
		Policy: policy(),
	}
	for d := 0; d < historyDays; d++ {
		p.History.Dates = append(p.History.Dates, start.AddDate(0, 0, d).Format(dayFormat))
	}

	for i, s := range catalog {
		// One random stream per product, so editing one product never shifts
		// another's history.
		rng := rand.New(rand.NewSource(seed + int64(i)))
		sched := pricing.PriceSchedule{Levels: s.levels, HoldDays: s.hold} // PromoEvery 0: no promotions
		current := s.levels[((historyDays-1)/s.hold)%len(s.levels)]
		m := pricing.DemandModel{
			SKUID: s.handle, Elasticity: s.beta,
			BaseLogDemand:   math.Log(s.baseUnits) - s.beta*math.Log(float64(current)/100),
			WeeklySeasonAmp: 0.20, AnnualSeasonAmp: 0.15, NoiseSD: 0.15, // PromoLift 0
		}
		obs := m.Generate(sched, historyDays, rng)
		if len(obs) != historyDays {
			return Plan{}, fmt.Errorf("%s: generated %d observations, want %d", s.handle, len(obs), historyDays)
		}
		pr := Product{
			Handle: s.handle, Title: s.title, ProductType: s.ptype, Tags: s.tags, SKU: s.sku,
			PriceCents: int64(obs[historyDays-1].Price), TrueElasticity: s.beta, Notes: s.notes,
			Schedule: Schedule{HoldDays: s.hold},
		}
		if s.cost > 0 {
			c := s.cost
			pr.UnitCostCents = &c
		}
		for _, l := range s.levels {
			pr.Schedule.Levels = append(pr.Schedule.Levels, int64(l))
		}
		total := 0
		for _, o := range obs {
			pr.Prices = append(pr.Prices, int64(o.Price))
			pr.Units = append(pr.Units, o.Units)
			total += o.Units
			if o.Units == 0 {
				pr.ZeroUnitDays++
			}
		}
		pr.MeanUnitsPerDay = math.Round(float64(total)/historyDays*100) / 100
		p.Products = append(p.Products, pr)
	}

	exp, err := runEngine(p, now)
	if err != nil {
		return Plan{}, err
	}
	p.Expected = exp
	return p, nil
}

// ---- running the engine ----------------------------------------------------

type estResp struct {
	OK    bool   `json:"ok"`
	Error string `json:"error"`
	Out   struct {
		Results []struct {
			SKUID    string `json:"sku_id"`
			Estimate struct {
				Elasticity   *float64 `json:"elasticity"`
				CILow        *float64 `json:"ci_low"`
				CIHigh       *float64 `json:"ci_high"`
				Method       string   `json:"method"`
				Refusal      string   `json:"refusal"`
				ConfidenceBP int32    `json:"confidence_bp"`
			} `json:"estimate"`
			Proposal         *enforcer.Proposal `json:"proposal"`
			NoProposalReason string             `json:"no_proposal_reason"`
			NoProposalCode   string             `json:"no_proposal_code"`
		} `json:"results"`
	} `json:"out"`
}

type decResp struct {
	OK    bool   `json:"ok"`
	Error string `json:"error"`
	Out   struct {
		PolicyHash string `json:"policy_hash"`
		Decisions  []struct {
			enforcer.Decision
		} `json:"decisions"`
	} `json:"out"`
}

func call(op string, in any, out any) error {
	req, err := json.Marshal(map[string]any{"op": op, "in": in})
	if err != nil {
		return err
	}
	resp, herr := bridge.Handle(req)
	if herr != nil {
		return fmt.Errorf("bridge %s: %v", op, herr)
	}
	return json.Unmarshal(resp, out)
}

func r4(f *float64) *float64 {
	if f == nil {
		return nil
	}
	v := math.Round(*f*10000) / 10000
	return &v
}

// runEngine feeds the plan to the engine exactly as the app will: sku id is the
// handle, group is the product type, observation day is days since the epoch,
// last_price_change_at is the zero time, now is the run date at 12:00 UTC.
func runEngine(p Plan, now time.Time) (Expected, error) {
	start, _ := time.Parse(dayFormat, p.History.Start)
	startDay := epochDay(start)

	type obsIn struct {
		Day     int   `json:"day"`
		Price   int64 `json:"price"`
		Units   int   `json:"units"`
		OnPromo bool  `json:"on_promo"`
	}
	type skuIn struct {
		SKU          enforcer.SKUState `json:"sku"`
		Group        string            `json:"group"`
		Observations []obsIn           `json:"observations"`
	}
	var skus []skuIn
	states := map[string]enforcer.SKUState{}
	for _, pr := range p.Products {
		st := enforcer.SKUState{
			ID: pr.Handle, VariantGID: "gid://shopify/ProductVariant/" + pr.Handle,
			CurrentPrice: enforcer.Cents(pr.PriceCents), Tags: append([]string{}, pr.Tags...), Collections: []string{},
			LastPriceChangeAt: time.Time{},
		}
		if pr.UnitCostCents != nil {
			st.UnitCost = enforcer.Cents(*pr.UnitCostCents)
		}
		states[pr.Handle] = st
		in := skuIn{SKU: st, Group: pr.ProductType}
		for d := range pr.Prices {
			in.Observations = append(in.Observations, obsIn{Day: startDay + d, Price: pr.Prices[d], Units: pr.Units[d]})
		}
		skus = append(skus, in)
	}

	var er estResp
	if err := call("estimate", map[string]any{"skus": skus}, &er); err != nil {
		return Expected{}, err
	}
	if !er.OK {
		return Expected{}, fmt.Errorf("estimate: %s", er.Error)
	}

	var items []enforcer.Item
	for _, r := range er.Out.Results {
		if r.Proposal != nil {
			items = append(items, enforcer.Item{SKU: states[r.SKUID], Proposal: *r.Proposal})
		}
	}
	decisions := map[string]enforcer.Decision{}
	hash := ""
	if len(items) > 0 {
		var dr decResp
		if err := call("decide", enforcer.Request{Policy: p.Policy, Now: now, Items: items}, &dr); err != nil {
			return Expected{}, err
		}
		if !dr.OK {
			return Expected{}, fmt.Errorf("decide: %s", dr.Error)
		}
		hash = dr.Out.PolicyHash
		for _, d := range dr.Out.Decisions {
			decisions[d.SKUID] = d.Decision
		}
	}

	exp := Expected{Summary: ExpectedSummary{Products: len(p.Products), RejectedByRule: map[string]int{}, PolicyHash: hash}}
	for _, r := range er.Out.Results {
		e := r.Estimate
		ep := ExpectedProduct{
			Handle: r.SKUID, Method: e.Method, Refusal: e.Refusal,
			Elasticity: r4(e.Elasticity), CILow: r4(e.CILow), CIHigh: r4(e.CIHigh), ConfidenceBP: e.ConfidenceBP,
			NoProposalReason: r.NoProposalReason, NoProposalCode: r.NoProposalCode,
			CurrentPrice: int64(states[r.SKUID].CurrentPrice),
		}
		if e.Method != "refused" {
			exp.Summary.Estimated++
		}
		if r.Proposal != nil {
			exp.Summary.Proposals++
			pp := int64(r.Proposal.ProposedPrice)
			ep.ProposalPrice = &pp
			d := decisions[r.SKUID]
			ep.Action = string(d.Action)
			ep.DecidingRule = decidingRule(d)
			switch d.Action {
			case enforcer.ActionReject:
				exp.Summary.Rejected++
				exp.Summary.RejectedByRule[ep.DecidingRule]++
			case enforcer.ActionApprove, enforcer.ActionClamp:
				if d.Action == enforcer.ActionApprove {
					exp.Summary.Approved++
				} else {
					exp.Summary.Clamped++
				}
				fp := int64(d.FinalPrice)
				ep.FinalPrice = &fp
				if fp != ep.CurrentPrice {
					exp.Summary.PriceChanges++
				}
			}
		}
		ep.Outcome = outcome(ep)
		exp.Products = append(exp.Products, ep)
	}
	return exp, nil
}

// decidingRule names the rule that decided the outcome: for a reject, the
// rule that blocked it; for a clamp, the guardrail that moved the price
// (rounding only if nothing else did); empty for a clean approval.
func decidingRule(d enforcer.Decision) string {
	switch d.Action {
	case enforcer.ActionReject:
		for _, r := range d.Reasons {
			if r.Effect == enforcer.EffectBlocked {
				return string(r.Rule)
			}
		}
		if n := len(d.Reasons); n > 0 {
			return string(d.Reasons[n-1].Rule)
		}
	case enforcer.ActionClamp:
		for _, r := range d.Reasons {
			if r.Effect == enforcer.EffectClamped && r.Rule != enforcer.RuleRounding {
				return string(r.Rule)
			}
		}
		for _, r := range d.Reasons {
			if r.Effect == enforcer.EffectClamped {
				return string(r.Rule)
			}
		}
	}
	return ""
}

func outcome(e ExpectedProduct) string {
	switch {
	case e.Method == "refused":
		return "refused: " + e.Refusal
	case e.ProposalPrice == nil && e.NoProposalCode != "":
		return "no proposal: " + e.NoProposalCode
	case e.ProposalPrice == nil:
		return "no proposal: missing unit cost"
	case e.Action == "reject":
		return "rejected: " + e.DecidingRule
	case e.FinalPrice != nil && *e.FinalPrice == e.CurrentPrice:
		return e.Action + ": no price change"
	case e.Action == "clamp" && e.DecidingRule != "rounding" && e.DecidingRule != "":
		return "clamped: " + e.DecidingRule
	default:
		return e.Action + ": price change"
	}
}

