// Check returns what is missing from the plan's expected outcome. The list is
// the review screen's minimum cast; it is not weakened to make a catalog pass.
func Check(p Plan) []string {
	var miss []string
	var clamp, excluded, infeasible, changes, fewPrices, lowVol, noCost int
	for _, e := range p.Expected.Products {
		switch {
		case e.Refusal == "too_few_distinct_prices":
			fewPrices++
		case e.Refusal == "volume_too_low":
			lowVol++
		case e.ProposalPrice == nil && e.NoProposalCode == "" && e.Method != "refused":
			noCost++
		}
		if e.Action == "reject" && e.DecidingRule == "excluded" {
			excluded++
		}
		if e.Action == "reject" && e.DecidingRule == "infeasible_bounds" {
			infeasible++
		}
		if e.Action == "clamp" && e.DecidingRule != "" && e.DecidingRule != "rounding" {
			clamp++
		}
		if (e.Action == "approve" || e.Action == "clamp") && e.FinalPrice != nil && *e.FinalPrice != e.CurrentPrice {
			changes++
		}
	}
	need := func(n, min int, what string) {
		if n < min {
			miss = append(miss, fmt.Sprintf("need at least %d %s, have %d", min, what, n))
		}
	}
	need(clamp, 1, "clamp by a guardrail (not just rounding)")
	need(excluded, 1, "reject by excluded")
	need(infeasible, 1, "reject by infeasible_bounds")
	need(changes, 3, "approve-or-clamp decisions that change a price")
	need(fewPrices, 1, "refusal too_few_distinct_prices")
	need(lowVol, 1, "refusal volume_too_low")
	need(noCost, 1, "no-proposal for missing cost")

	// Volume and variation guarantees for the products meant to be estimable.
	byHandle := map[string]Product{}
	for _, pr := range p.Products {
		byHandle[pr.Handle] = pr
	}
	for _, s := range catalog {
		pr := byHandle[s.handle]
		if len(pr.Prices) != historyDays || len(pr.Units) != historyDays {
			miss = append(miss, s.handle+": history is not exactly 90 days")
		}
		if !s.estimable {
			continue
		}
		if pr.MeanUnitsPerDay < minEstimableUnits {
			miss = append(miss, fmt.Sprintf("%s: mean %.1f units a day, need at least %.0f", s.handle, pr.MeanUnitsPerDay, minEstimableUnits))
		}
		distinct := map[int64]bool{}
		for _, x := range pr.Prices {
			distinct[x] = true
		}
		if len(distinct) < 4 {
			miss = append(miss, fmt.Sprintf("%s: %d distinct prices, need at least 4", s.handle, len(distinct)))
		}
	}
	for _, e := range p.Expected.Products {
		if s := specFor(e.Handle); s != nil && s.estimable && e.Method == "refused" {
			miss = append(miss, fmt.Sprintf("%s: meant to be estimable but refused (%s)", e.Handle, e.Refusal))
		}
	}
	return miss
}

func specFor(h string) *spec {
	for i := range catalog {
		if catalog[i].handle == h {
			return &catalog[i]
		}
	}
	return nil
}

// ---- output ----------------------------------------------------------------

var scalarArray = regexp.MustCompile(`\[\s*(?:(?:-?\d+(?:\.\d+)?|"[^"\s]*")\s*,?\s*)+\]`)
var spaces = regexp.MustCompile(`\s+`)

// render indents the JSON but keeps arrays of numbers and short strings on one
// line, so a 90-day series is one line, not ninety.
func render(v any) ([]byte, error) {
	raw, err := json.Marshal(v)
	if err != nil {
		return nil, err
	}
	var buf bytes.Buffer
	if err := json.Indent(&buf, raw, "", "  "); err != nil {
		return nil, err
	}
	out := scalarArray.ReplaceAllFunc(buf.Bytes(), func(m []byte) []byte {
		s := spaces.ReplaceAllString(string(m), "")
		return []byte(strings.ReplaceAll(s, ",", ", "))
	})
	return append(out, '\n'), nil
}

func table(w io.Writer, p Plan) {
	fmt.Fprintf(w, "\n  %-28s %-34s %9s %9s %9s  %s\n", "product", "outcome", "est beta", "current", "final", "rule")
	for _, e := range p.Expected.Products {
		est, fin := "-", "-"
		if e.Elasticity != nil && e.Method != "refused" {
			est = fmt.Sprintf("%.2f", *e.Elasticity)
		}
		if e.FinalPrice != nil {
			fin = fmt.Sprintf("%d", *e.FinalPrice)
		}
		fmt.Fprintf(w, "  %-28s %-34s %9s %9d %9s  %s\n", e.Handle, e.Outcome, est, e.CurrentPrice, fin, e.DecidingRule)
	}
	s := p.Expected.Summary
	rules := make([]string, 0)
	for r, n := range s.RejectedByRule {
		rules = append(rules, fmt.Sprintf("%s x%d", r, n))
	}
	sort.Strings(rules)
	fmt.Fprintf(w, "\n  %d products, %d estimated, %d proposals, %d approved, %d clamped, %d rejected (%s), %d price changes\n",
		s.Products, s.Estimated, s.Proposals, s.Approved, s.Clamped, s.Rejected, strings.Join(rules, ", "), s.PriceChanges)
}

func main() { os.Exit(run(os.Args[1:], os.Stdout, os.Stderr)) }

func run(args []string, stdout, stderr io.Writer) int {
	fs := flag.NewFlagSet("seedplan", flag.ContinueOnError)
	fs.SetOutput(stderr)
	endFlag := fs.String("end", "", "run date YYYY-MM-DD; history is the 90 days ending the day before (default: today, UTC)")
	out := fs.String("out", "", "write the plan JSON to this file instead of stdout")
	check := fs.Bool("check", false, "print the expected-outcome table and exit non-zero unless the required cases are present")
	if err := fs.Parse(args); err != nil {
		return 2
	}
	end := time.Now().UTC()
	if *endFlag != "" {
		t, err := time.Parse(dayFormat, *endFlag)
		if err != nil {
			fmt.Fprintln(stderr, "seedplan: bad -end:", err)
			return 2
		}
		end = t
	}
	p, err := Build(end)
	if err != nil {
		fmt.Fprintln(stderr, "seedplan:", err)
		return 1
	}
	if *check {
		table(stdout, p)
		if miss := Check(p); len(miss) > 0 {
			fmt.Fprintln(stdout, "\n  CHECK FAILED")
			for _, m := range miss {
				fmt.Fprintln(stdout, "   -", m)
			}
			return 1
		}
		fmt.Fprintln(stdout, "\n  CHECK PASSED")
		return 0
	}
	b, err := render(p)
	if err != nil {
		fmt.Fprintln(stderr, "seedplan:", err)
		return 1
	}
	if *out != "" {
		if err := os.WriteFile(*out, b, 0o644); err != nil {
			fmt.Fprintln(stderr, "seedplan:", err)
			return 1
		}
		return 0
	}
	stdout.Write(b)
	return 0
}
