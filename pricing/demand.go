package pricing

import (
	"math"
	"math/rand"

	"github.com/gkhurana21/pricepilot/enforcer"
)

// Observation is one day of sales for one SKU.
type Observation struct {
	Day     int
	Price   enforcer.Cents
	Units   int
	OnPromo bool
}

// DemandModel is a constant-elasticity demand curve with known parameters.
//
//	log E[units] = BaseLogDemand + Elasticity*log(price)
//	             + weekly seasonality + annual seasonality
//	             + PromoLift (on promo days)
//	             + N(0, NoiseSD^2)
//
// This exists so the estimator can be held to a standard no real dataset can
// provide: with real merchant data you can measure that an estimate is stable,
// never that it is *right*. Here Elasticity is known, so recovery is a
// measurable property rather than a hope.
type DemandModel struct {
	SKUID           string
	BaseLogDemand   float64
	Elasticity      float64 // the ground truth, typically -1 to -4
	WeeklySeasonAmp float64
	AnnualSeasonAmp float64

	// PromoLift is the demand a promotion adds beyond the price cut itself —
	// the email blast, the homepage banner. It is the confounder that matters:
	// promos lower price and raise demand at the same time, so an estimator
	// that ignores them attributes the whole lift to elasticity and reports
	// demand as far more price-sensitive than it is.
	PromoLift float64

	NoiseSD float64
}

// PriceSchedule describes how a merchant actually moved the price. Elasticity
// is identified by variation in this schedule, not by the number of orders, so
// it is the single most important input to whether an estimate is possible.
type PriceSchedule struct {
	Levels   []enforcer.Cents
	HoldDays int // days at each level before moving to the next

	// PromoEvery schedules a promotion every N days lasting PromoDays, at
	// PromoDiscountBP off the current level. Zero disables promotions.
	PromoEvery      int
	PromoDays       int
	PromoDiscountBP enforcer.BasisPoints
}

// Generate simulates daily orders.
//
// Counts are Poisson draws around a lognormally-shocked mean rather than a
// clean lognormal. That makes the data mildly misspecified relative to the
// log-log model the estimator fits, which is the point: order counts really are
// discrete and overdispersed, and an estimator that only recovers truth from
// data generated by its own assumptions has not been tested.
func (m DemandModel) Generate(sched PriceSchedule, days int, rng *rand.Rand) []Observation {
	if len(sched.Levels) == 0 || sched.HoldDays <= 0 || days <= 0 {
		return nil
	}

	obs := make([]Observation, 0, days)
	for day := 0; day < days; day++ {
		level := sched.Levels[(day/sched.HoldDays)%len(sched.Levels)]

		onPromo := false
		price := level
		if sched.PromoEvery > 0 && sched.PromoDays > 0 {
			if day%sched.PromoEvery < sched.PromoDays {
				onPromo = true
				keep := enforcer.OneHundredPercent - sched.PromoDiscountBP
				price = enforcer.Cents(int64(level) * int64(keep) / int64(enforcer.OneHundredPercent))
			}
		}
		if price <= 0 {
			continue
		}

		logLambda := m.BaseLogDemand +
			m.Elasticity*math.Log(float64(price)/100) +
			m.WeeklySeasonAmp*math.Sin(2*math.Pi*float64(day)/7) +
			m.AnnualSeasonAmp*math.Sin(2*math.Pi*float64(day)/365)
		if onPromo {
			logLambda += m.PromoLift
		}
		logLambda += rng.NormFloat64() * m.NoiseSD

		units := poisson(rng, math.Exp(logLambda))
		if units <= 0 {
			// A zero-unit day carries no information for a log-log fit and
			// cannot be logged. Dropping it is a real limitation, recorded in
			// the estimate as ZeroDays so it is visible rather than hidden.
			continue
		}

		obs = append(obs, Observation{Day: day, Price: price, Units: units, OnPromo: onPromo})
	}
	return obs
}

// poisson draws from Poisson(lambda): Knuth's product method for small means,
// and a normal approximation with continuity correction for large ones, where
// Knuth would need thousands of multiplications per draw.
func poisson(rng *rand.Rand, lambda float64) int {
	if lambda <= 0 || math.IsNaN(lambda) {
		return 0
	}
	if lambda > 500 {
		v := rng.NormFloat64()*math.Sqrt(lambda) + lambda
		return int(math.Round(math.Max(0, v)))
	}
	l := math.Exp(-lambda)
	k, p := 0, 1.0
	for {
		p *= rng.Float64()
		if p <= l {
			return k
		}
		k++
		if k > 100_000 {
			return k
		}
	}
}
